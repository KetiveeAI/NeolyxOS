#!/usr/bin/env python3
"""
Generates sdk/libc/src/math/constants.h: the mathematical constants nxlibc's
math functions need, to full long double (64-bit significand) precision.

Everything is computed here from first principles with Python's decimal
module (pi from Machin's formula, ln 2 and ln 10 from series), so the
constants can be re-derived and checked by anyone.

Usage: python3 gen_math_constants.py > ../src/math/constants.h

Copyright (c) 2025 KetiveeAI
SPDX-License-Identifier: MIT
"""
from decimal import Decimal, getcontext
from fractions import Fraction

getcontext().prec = 520


def atan_inv(n):
    """atan(1/n) by its Taylor series"""
    x = Decimal(1) / n
    x2 = x * x
    term, total, k = x, x, 1
    eps = Decimal(10) ** (-getcontext().prec + 5)
    while True:
        term *= -x2
        k += 2
        t = term / k
        if abs(t) < eps:
            break
        total += t
    return total


def ln_series(y):
    """ln(y) for y near 1 via 2*atanh((y-1)/(y+1))"""
    s = (y - 1) / (y + 1)
    s2 = s * s
    term, total, k = s, s, 1
    eps = Decimal(10) ** (-getcontext().prec + 5)
    while True:
        term *= s2
        k += 2
        t = term / k
        if abs(t) < eps:
            break
        total += t
    return 2 * total


PI = 16 * atan_inv(5) - 4 * atan_inv(239)
LN2 = ln_series(Decimal(2))
LN10 = 3 * LN2 + ln_series(Decimal(10) / 8)


def to_fraction(d):
    return Fraction(d)


def ld_hex(value, bits=64):
    """Nearest long double (64-bit significand) as a C hex literal"""
    f = Fraction(value)
    if f == 0:
        return "0.0L"
    sign = "-" if f < 0 else ""
    f = abs(f)
    e = 0
    while f >= 2:
        f /= 2
        e += 1
    while f < 1:
        f *= 2
        e -= 1
    m = f * (1 << (bits - 1))
    mi = int(m)
    rem = m - mi
    if rem > Fraction(1, 2) or (rem == Fraction(1, 2) and mi & 1):
        mi += 1
    if mi == 1 << bits:
        mi >>= 1
        e += 1
    # mi has 64 bits: leading 1 then 63 fraction bits -> print as 1.<hex>p
    frac = mi - (1 << (bits - 1))
    hexfrac = format(frac << 1, "016x")  # 64 bits after the point
    return f"{sign}0x1.{hexfrac}p{e}L"


def ld_value(value, bits=64):
    """The exact Fraction that ld_hex rounds to"""
    f = Fraction(value)
    if f == 0:
        return Fraction(0)
    sign = -1 if f < 0 else 1
    f = abs(f)
    e = 0
    while f >= 2:
        f /= 2
        e += 1
    while f < 1:
        f *= 2
        e -= 1
    m = f * (1 << (bits - 1))
    mi = int(m)
    rem = m - mi
    if rem > Fraction(1, 2) or (rem == Fraction(1, 2) and mi & 1):
        mi += 1
    return sign * Fraction(mi, 1 << (bits - 1)) * (Fraction(2) ** e)


def truncate_bits(value, frac_bits):
    """value rounded to a multiple of 2^-frac_bits"""
    f = Fraction(value) * (1 << frac_bits)
    return Fraction(round(f), 1 << frac_bits)


pi = to_fraction(PI)
ln2 = to_fraction(LN2)
ln10 = to_fraction(LN10)
pio2 = pi / 2

out = []
out.append("/* Generated by sdk/libc/tools/gen_math_constants.py - do not edit. */")
out.append("#ifndef NXLIBC_MATH_CONSTANTS_H")
out.append("#define NXLIBC_MATH_CONSTANTS_H")
out.append("#include <stdint.h>")
out.append("")
out.append(f"#define NXC_PI_L      {ld_hex(pi)}")
out.append(f"#define NXC_PIO2_L    {ld_hex(pio2)}")
out.append(f"#define NXC_PIO4_L    {ld_hex(pi / 4)}")
out.append(f"#define NXC_LN2_L     {ld_hex(ln2)}")
out.append(f"#define NXC_LOG2E_L   {ld_hex(1 / ln2)}")
out.append(f"#define NXC_LN10_L    {ld_hex(ln10)}")
out.append(f"#define NXC_LOG10E_L  {ld_hex(1 / ln10)}")
out.append(f"#define NXC_INVPIO2_L {ld_hex(2 / pi)}")
out.append("")
# ln2 split: hi has 48 fraction bits so k*hi is exact for |k| < 2^16
ln2_hi = truncate_bits(ln2, 48)
ln2_lo = ln2 - ln2_hi
out.append("/* ln 2 = HI + LO; HI has 48 significant bits, so k * HI is exact for |k| < 2^16 */")
out.append(f"#define NXC_LN2_HI_L  {ld_hex(ln2_hi)}")
out.append(f"#define NXC_LN2_LO_L  {ld_hex(ln2_lo)}")
out.append("")
# pi/2 in three pieces of 43 bits each (Cody-Waite), for |q| < 2^20
p1 = truncate_bits(pio2, 42)        # pio2 < 2 -> 43 significant bits
p2 = truncate_bits(pio2 - p1, 42 + 43)
p3 = pio2 - p1 - p2
out.append("/* pi/2 = P1 + P2 + P3; P1 and P2 have 43 significant bits each, so q * P1")
out.append(" * and q * P2 are exact in long double for |q| < 2^21 */")
out.append(f"#define NXC_PIO2_P1_L {ld_hex(p1)}")
out.append(f"#define NXC_PIO2_P2_L {ld_hex(p2)}")
out.append(f"#define NXC_PIO2_P3_L {ld_hex(p3)}")
out.append("")
# 2/pi as 1344 fraction bits in 32-bit words
nwords = 42
two_over_pi = 2 / pi
words = []
f = two_over_pi
for _ in range(nwords):
    f *= 1 << 32
    w = int(f)
    words.append(w)
    f -= w
out.append(f"/* Binary digits of 2/pi after the point, 32 per word, most significant first */")
out.append(f"#define NXC_TWO_OVER_PI_WORDS {nwords}")
out.append("static const uint32_t nxc_two_over_pi[NXC_TWO_OVER_PI_WORDS] = {")
for i in range(0, nwords, 6):
    out.append("    " + ", ".join(f"0x{w:08X}u" for w in words[i:i + 6]) + ",")
out.append("};")
out.append("")
# inverse factorials
out.append("/* 1/k! for k = 0..27 */")
out.append("static const long double nxc_inv_fact[28] = {")
fact = Fraction(1)
for k in range(28):
    if k > 0:
        fact *= k
    out.append(f"    {ld_hex(1 / fact)},")
out.append("};")
out.append("")
out.append("#endif /* NXLIBC_MATH_CONSTANTS_H */")
print("\n".join(out))
