#!/usr/bin/env python3
# Generate tls_fixture.h for cryptotest from the downloaded RFC 8448 trace
# (tests/host/crypto_fetch_vectors.sh, rfc8448/transcripts.vec). The
# fixture is the RFC 8448 section 3 "Simple 1-RTT Handshake": the records
# and the client's X25519 private key, so cryptotest can replay the key
# schedule and record protection inside NeolyxOS. It is generated at
# build time so no trace data is stored in the tree.
#
# Usage: gen_tls_fixture.py <path to transcripts.vec> <output header>
#
