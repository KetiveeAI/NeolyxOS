# SPDX-License-Identifier: MIT

import re
import sys

SECTION = "Simple_1RTT_Handshake"


def load(path):
    sections, cur = {}, None
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            m = re.fullmatch(r"\[(.+)\]", line)
            if m:
                cur = sections.setdefault(m.group(1), {})
                continue
            if cur is None or "=" not in line:
                continue
            k, v = (x.strip() for x in line.split("=", 1))
            v = re.sub(r"\s+", "", v)
            if re.fullmatch(r"(?:[0-9a-fA-F]{2})+", v):
                cur[k] = bytes.fromhex(v)
    return sections


def c_array(name, data):
    lines = [f"static const uint8_t {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def server_key_share(sh):
    i = 4 + 2 + 32
    i += 1 + sh[i]          # legacy_session_id_echo
    suite = sh[i] << 8 | sh[i + 1]
    i += 3                  # cipher_suite, legacy_compression_method
    end = i + 2 + (sh[i] << 8 | sh[i + 1])
    i += 2
    while i + 4 <= end:
        t, n = sh[i] << 8 | sh[i + 1], sh[i + 2] << 8 | sh[i + 3]
        if t == 0x0033:
            body = sh[i + 4:i + 4 + n]
            if body[:4] != b"\x00\x1d\x00\x20":
                sys.exit("gen_tls_fixture: server key share is not X25519")
            return suite, body[4:]
        i += 4 + n
    sys.exit("gen_tls_fixture: no key_share in ServerHello")


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: gen_tls_fixture.py <transcripts.vec> <out.h>")
    s = load(sys.argv[1]).get(SECTION)
    need = ["Record_ClientHello_1", "Message_ServerHello", "Client_RNG_Pool",
            "Record_ServerHandshakeMessages", "Message_EncryptedExtensions",
            "Message_Server_Certificate", "Message_Server_CertificateVerify",
            "Message_Server_Finished", "Record_ClientFinished", "Record_NewSessionTicket",
            "Server_AppData", "Record_Server_AppData", "Client_AppData", "Record_Client_AppData"]
    if s is None or any(k not in s for k in need):
        sys.exit(f"gen_tls_fixture: {SECTION} missing or incomplete")
    ch = s["Record_ClientHello_1"][5:]
    if ch[4 + 2 + 32] != 0:
        sys.exit("gen_tls_fixture: expected an empty session id")
    suite, server_pub = server_key_share(s["Message_ServerHello"])
    flight = (s["Message_EncryptedExtensions"] + s["Message_Server_Certificate"] +
              s["Message_Server_CertificateVerify"])
    out = [
        "/* Generated by gen_tls_fixture.py from the RFC 8448 trace; do not edit. */",
        f"/* RFC 8448 section 3, {SECTION} */",
        f"#define TLS_FIXTURE_SUITE 0x{suite:04x}u",
        c_array("TLS_CLIENT_HELLO", ch),
        c_array("TLS_SERVER_HELLO", s["Message_ServerHello"]),
        c_array("TLS_CLIENT_PRIV", s["Client_RNG_Pool"][32:64]),
        c_array("TLS_SERVER_PUB", server_pub),
        c_array("TLS_SERVER_FLIGHT_REC", s["Record_ServerHandshakeMessages"]),
        c_array("TLS_SERVER_MSGS", flight),
        c_array("TLS_SERVER_FINISHED", s["Message_Server_Finished"]),
        c_array("TLS_CLIENT_FINISHED_REC", s["Record_ClientFinished"]),
        c_array("TLS_NST_REC", s["Record_NewSessionTicket"]),
        c_array("TLS_SERVER_APP_REC", s["Record_Server_AppData"]),
        c_array("TLS_SERVER_APP", s["Server_AppData"]),
        c_array("TLS_CLIENT_APP", s["Client_AppData"]),
        c_array("TLS_CLIENT_APP_REC", s["Record_Client_AppData"]),
        "",
    ]
    with open(sys.argv[2], "w", encoding="utf-8") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
