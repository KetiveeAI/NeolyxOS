#!/usr/bin/env python3
# Generate x509_fixture.h for cryptotest from the downloaded x509-limbo
# vectors (tests/host/crypto_fetch_vectors.sh). The fixture is the
# "online::fastly.com" case: a real server chain (leaf, intermediate,
# root) and its validation time. It is generated at build time so no
# certificate data is stored in the tree.
#
# Usage: gen_x509_fixture.py <path to limbo.json> <output header>
#
