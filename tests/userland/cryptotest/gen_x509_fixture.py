import base64
import datetime
import json
import sys

CASE = "online::fastly.com"


def pem_to_der(pem):
    body = "".join(l for l in pem.strip().splitlines() if not l.startswith("-----"))
    return base64.b64decode(body, validate=True)


def c_array(name, data):
    lines = [f"static const uint8_t {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: gen_x509_fixture.py <limbo.json> <out.h>")
    with open(sys.argv[1], encoding="utf-8") as f:
        cases = {t["id"]: t for t in json.load(f)["testcases"]}
    t = cases.get(CASE)
    if t is None or t["expected_result"] != "SUCCESS":
        sys.exit(f"gen_x509_fixture: {CASE} missing or not a SUCCESS case")
    if len(t["trusted_certs"]) != 1 or len(t["untrusted_intermediates"]) != 1:
        sys.exit(f"gen_x509_fixture: {CASE} no longer has a 3-certificate chain")
    when = datetime.datetime.fromisoformat(t["validation_time"])
    out = [
        "/* Generated by gen_x509_fixture.py from x509-limbo; do not edit. */",
        f"/* Case {CASE}: {t['expected_peer_name']['value']} */",
        f"#define FIXTURE_HOST \"{t['expected_peer_name']['value']}\"",
        f"#define FIXTURE_TIME {int(when.timestamp())}LL",
        c_array("FIXTURE_LEAF", pem_to_der(t["peer_certificate"])),
        c_array("FIXTURE_INTERMEDIATE", pem_to_der(t["untrusted_intermediates"][0])),
        c_array("FIXTURE_ROOT", pem_to_der(t["trusted_certs"][0])),
        "",
    ]
    with open(sys.argv[2], "w", encoding="utf-8") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
