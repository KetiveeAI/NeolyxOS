#!/usr/bin/env python3
"""
NeolyxOS - boot splash asset builder

Renders the boot splash assets into one C header that the kernel splash
(kernel/src/video/splash.c) compiles in:

    kernel/src/video/splash_assets.h
        - the NeolyxOS logo (icons/neologo.png), pre-composited onto the
          splash background and stored as a 256-colour palette + indices
        - a small NXSans UI glyph atlas (printable ASCII, 8-bit coverage)
          so splash text uses the same typeface as the desktop

The kernel cannot link the desktop text engine (it is userspace code and
the kernel image has to stay small), so the splash gets pre-rasterised
assets instead. The kernel build never runs Python; the generated header
is committed. Re-run this after changing the logo, the font or the sizes.

Usage:  python3 tools/gen_boot_splash.py [--check]
        --check  rebuild in memory and fail if the committed header differs

Requires: Pillow with FreeType (pip install pillow).

Copyright (c) 2025-2026 KetiveeAI
"""

import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOGO_SRC = os.path.join(ROOT, "icons", "neologo.png")
FONT_SRC = os.path.join(ROOT, "resources", "fonts", "NXSans", "NXSans-UI.ttf")
OUT = os.path.join(ROOT, "kernel", "src", "video", "splash_assets.h")

# Must match SPLASH_BG in kernel/src/video/splash.c
BG_RGB = (0x0B, 0x0B, 0x12)
LOGO_HEIGHT = 120          # px at 1x; the kernel doubles it on HiDPI panels
FONT_PX = 15               # glyph atlas size
FIRST_CH, LAST_CH = 32, 126
# Light text on a dark background reads thin with linear coverage; lift
# mid-tones slightly (same idea as the desktop's polarity curve).
COVERAGE_GAMMA = 0.85
# NXSans UI's space is 0.2 em, which reads as no space at caption sizes
# without kerning context ("F2 for" -> "F2for"). Widen it a little.
MIN_SPACE_EM = 0.3


def build_logo():
    src = Image.open(LOGO_SRC).convert("RGBA")
    w = round(src.width * LOGO_HEIGHT / src.height)
    logo = src.resize((w, LOGO_HEIGHT), Image.LANCZOS)
    flat = Image.new("RGBA", logo.size, BG_RGB + (255,))
    flat.alpha_composite(logo)
    rgb = flat.convert("RGB")
    pal_img = rgb.quantize(colors=256, method=Image.MEDIANCUT, dither=Image.NONE)
    palette = pal_img.getpalette()[: 256 * 3]
    indices = list(pal_img.tobytes())
    ncolors = max(indices) + 1
    colors = [
        (palette[i * 3] << 16) | (palette[i * 3 + 1] << 8) | palette[i * 3 + 2]
        for i in range(ncolors)
    ]
    # Pad to 256 entries so every uint8_t index is in range
    colors += [(BG_RGB[0] << 16) | (BG_RGB[1] << 8) | BG_RGB[2]] * (256 - len(colors))
    return w, LOGO_HEIGHT, colors, indices


def build_font():
    font = ImageFont.truetype(FONT_SRC, FONT_PX)
    ascent, descent = font.getmetrics()
    glyphs = []
    data = []
    for code in range(FIRST_CH, LAST_CH + 1):
        ch = chr(code)
        # Advance in 1/64 px so the kernel can accumulate fractional widths
        adv = font.getlength(ch)
        if ch == " ":
            adv = max(adv, FONT_PX * MIN_SPACE_EM)
        adv64 = round(adv * 64)
        box = font.getbbox(ch)
        gw, gh = box[2] - box[0], box[3] - box[1]
        if gw <= 0 or gh <= 0:
            glyphs.append((len(data), 0, 0, 0, 0, adv64))
            continue
        img = Image.new("L", (gw, gh), 0)
        ImageDraw.Draw(img).text((-box[0], -box[1]), ch, font=font, fill=255)
        cov = [round(255 * (v / 255) ** COVERAGE_GAMMA) for v in img.tobytes()]
        glyphs.append((len(data), gw, gh, box[0], box[1], adv64))
        data.extend(cov)
    return ascent, descent, glyphs, data


def fmt_array(values, per_line, width):
    lines = []
    for i in range(0, len(values), per_line):
        chunk = values[i : i + per_line]
        lines.append("    " + ",".join(width.format(v) for v in chunk) + ",")
    return "\n".join(lines)


def render():
    lw, lh, colors, indices = build_logo()
    ascent, descent, glyphs, gdata = build_font()
    out = []
    out.append("/*")
    out.append(" * NeolyxOS Kernel - Boot splash assets")
    out.append(" *")
    out.append(" * GENERATED by tools/gen_boot_splash.py - do not edit by hand.")
    out.append(" * Sources: icons/neologo.png, resources/fonts/NXSans/NXSans-UI.ttf")
    out.append(" *")
    out.append(" * Copyright (c) 2025-2026 KetiveeAI")
    out.append(" */")
    out.append("")
    out.append("#ifndef NEOLYXOS_SPLASH_ASSETS_H")
    out.append("#define NEOLYXOS_SPLASH_ASSETS_H")
    out.append("")
    out.append("#include <stdint.h>")
    out.append("")
    out.append("/* Logo: palette indices, pre-composited on 0x%02X%02X%02X */" % BG_RGB)
    out.append("#define SPLASH_LOGO_W %d" % lw)
    out.append("#define SPLASH_LOGO_H %d" % lh)
    out.append("")
    out.append("static const uint32_t splash_logo_palette[256] = {")
    out.append(fmt_array(colors, 8, "0x{:06X}"))
    out.append("};")
    out.append("")
    out.append("static const uint8_t splash_logo_pixels[SPLASH_LOGO_W * SPLASH_LOGO_H] = {")
    out.append(fmt_array(indices, 24, "{}"))
    out.append("};")
    out.append("")
    out.append("/* NXSans UI %dpx glyph atlas, ASCII %d..%d, 8-bit coverage */" % (FONT_PX, FIRST_CH, LAST_CH))
    out.append("#define SPLASH_FONT_PX %d" % FONT_PX)
    out.append("#define SPLASH_FONT_ASCENT %d" % ascent)
    out.append("#define SPLASH_FONT_DESCENT %d" % descent)
    out.append("#define SPLASH_FONT_FIRST %d" % FIRST_CH)
    out.append("#define SPLASH_FONT_LAST %d" % LAST_CH)
    out.append("")
    out.append("typedef struct {")
    out.append("    uint16_t offset;   /* into splash_font_data */")
    out.append("    uint8_t  w, h;     /* bitmap size */")
    out.append("    int8_t   x, y;     /* bitmap origin relative to pen / line top */")
    out.append("    uint16_t adv64;    /* advance in 1/64 px */")
    out.append("} splash_glyph_t;")
    out.append("")
    out.append("static const splash_glyph_t splash_font_glyphs[SPLASH_FONT_LAST - SPLASH_FONT_FIRST + 1] = {")
    for code, g in zip(range(FIRST_CH, LAST_CH + 1), glyphs):
        name = "' '" if code == 32 else ("'\\\\'" if code == 92 else ("'\\''" if code == 39 else "'%s'" % chr(code)))
        out.append("    {%d, %d, %d, %d, %d, %d}, /* %s */" % (g + (name,)))
    out.append("};")
    out.append("")
    out.append("static const uint8_t splash_font_data[%d] = {" % len(gdata))
    out.append(fmt_array(gdata, 24, "{}"))
    out.append("};")
    out.append("")
    out.append("#endif /* NEOLYXOS_SPLASH_ASSETS_H */")
    out.append("")
    assert len(gdata) < 65536, "glyph atlas exceeds uint16_t offsets"
    return "\n".join(out)


def main():
    check = "--check" in sys.argv[1:]
    text = render()
    if check:
        try:
            with open(OUT, "r", encoding="utf-8") as f:
                current = f.read()
        except OSError as e:
            print("error: cannot read %s: %s" % (OUT, e), file=sys.stderr)
            return 1
        if current != text:
            print("error: %s is out of date; run tools/gen_boot_splash.py" % OUT, file=sys.stderr)
            return 1
        print("splash assets up to date")
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s" % os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
