/*
 * NXCanvas - generator for nxc_srgb_lut.h (R2 linear-light edges)
 *
 * Writes the two lookup tables NXCanvas uses to blend anti-aliased edge
 * coverage in linear light. The engine is freestanding (no libm), so the
 * tables are generated on the host from the sRGB transfer function
 * (IEC 61966-2-1) and committed. Rebuild after changing this file:
 *
 *   gcc -std=c11 -O2 -Wall -Wextra -o /tmp/gen_srgb_lut \
 *       desktop/lib/nxcanvas/tools/gen_srgb_lut.c -lm
 *   /tmp/gen_srgb_lut > desktop/lib/nxcanvas/nxc_srgb_lut.h
 *
 * Tables:
 *   nxc__srgb_to_lin16[256]   8-bit sRGB -> linear, 0..65535
 *   nxc__lin12_to_srgb[4096]  (linear >> 4) -> 8-bit sRGB, each entry the
 *                             nearest sRGB value to the middle of its bucket
 * The generator checks that every sRGB value survives the round trip, and
 * fails (exit 1) if not, so an edge blended with itself is unchanged.
 *
 * Copyright (c) 2025 KetiveeAI
 * SPDX-License-Identifier: MIT
 */

#include <math.h>
#include <stdint.h>
#include <stdio.h>

static double decode(double v) {          /* sRGB -> linear, both 0..1 */
    return v <= 0.04045 ? v / 12.92 : pow((v + 0.055) / 1.055, 2.4);
}

static double encode(double l) {          /* linear -> sRGB, both 0..1 */
    if (l <= 0.0) return 0.0;
    if (l >= 1.0) return 1.0;
    return l <= 0.0031308 ? l * 12.92 : 1.055 * pow(l, 1.0 / 2.4) - 0.055;
}

int main(void) {
    uint16_t to_lin[256];
    uint8_t to_srgb[4096];
    for (int v = 0; v < 256; v++) {
        double l = decode(v / 255.0) * 65535.0;
        to_lin[v] = (uint16_t)floor(l + 0.5);
    }
    for (int i = 0; i < 4096; i++) {
        double l = ((double)i * 16.0 + 7.5) / 65535.0;
        double s = encode(l) * 255.0;
        int r = (int)floor(s + 0.5);
        to_srgb[i] = (uint8_t)(r < 0 ? 0 : r > 255 ? 255 : r);
    }
    for (int v = 0; v < 256; v++) {
        if (to_srgb[to_lin[v] >> 4] != v) {
            fprintf(stderr, "gen_srgb_lut: round trip fails for %d\n", v);
            return 1;
        }
    }

    printf("/*\n * NXCanvas sRGB <-> linear lookup tables (R2 linear-light edges).\n");
    printf(" * GENERATED by tools/gen_srgb_lut.c - do not edit by hand.\n");
    printf(" *\n * Copyright (c) 2025 KetiveeAI\n * SPDX-License-Identifier: MIT\n */\n\n");
    printf("#ifndef NXC_SRGB_LUT_H\n#define NXC_SRGB_LUT_H\n\n#include <stdint.h>\n\n");
    printf("/* 8-bit sRGB -> linear light, 0..65535 */\n");
    printf("static const uint16_t nxc__srgb_to_lin16[256] = {\n");
    for (int v = 0; v < 256; v++) {
        printf("%s%5u,%s", (v % 12 == 0) ? "    " : " ", to_lin[v], (v % 12 == 11 || v == 255) ? "\n" : "");
    }
    printf("};\n\n/* linear light >> 4 (0..4095) -> 8-bit sRGB */\n");
    printf("static const uint8_t nxc__lin12_to_srgb[4096] = {\n");
    for (int i = 0; i < 4096; i++) {
        printf("%s%3u,%s", (i % 16 == 0) ? "    " : " ", to_srgb[i], (i % 16 == 15) ? "\n" : "");
    }
    printf("};\n\n#endif /* NXC_SRGB_LUT_H */\n");
    return 0;
}
